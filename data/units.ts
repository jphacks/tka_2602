export function getUnit(id: string): HistoryUnit | undefined {
  return historyUnits.find((unit) => unit.id === id);
}

export function findUnitByCode(code: string): HistoryUnit | undefined {
  const normalized = code.trim().normalize("NFKC").replace(/\s+/g, "").toLowerCase();
  if (!normalized) return undefined;
  return historyUnits.find((unit) =>
    unit.textbookCodes.some((candidate) => candidate.toLowerCase() === normalized),
  );
}
